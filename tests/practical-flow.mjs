const baseline=structuredClone(defaultContent);
const draft=structuredClone(baseline);
draft.images.heroId='12345678-1234-4234-8234-123456789012';
draft.images.lightHeroId='12345678-1234-4234-8234-123456789013';
draft.theme.logoPosition='left';draft.theme.logoMobileWidth=120;draft.theme.logoDesktopWidth=200;
draft.invitation={enabled:false,heading:'Welcome to WIWW',message:'A personal welcome.'};
draft.business.services[0].inclusions=['Paint-safe wash','Wheel care'];
const restored=parseContent(JSON.stringify(contentSchema.parse(draft)));
assert.equal(restored.images.lightHeroId,draft.images.lightHeroId);
assert.equal(restored.theme.logoMobileWidth,120);assert.equal(restored.theme.logoDesktopWidth,200);
assert.equal(contentSchema.safeParse({...draft,theme:{...draft.theme,logoMobileWidth:500}}).success,false,'oversized mobile logos cannot be saved');
assert.equal(contentSchema.safeParse({...draft,theme:{...draft.theme,logoDesktopWidth:NaN}}).success,false,'non-numeric dimensions cannot be saved');
assert.equal(restored.theme.logoPosition,'left','the owner-selected logo position survives saving and loading');
const previousTheme=structuredClone(defaultContent);delete previousTheme.theme.logoPosition;
assert.equal(parseContent(JSON.stringify(previousTheme)).theme.logoPosition,'center','existing sites default to the requested centered header');
assert.equal(contentSchema.safeParse({...draft,theme:{...draft.theme,logoPosition:'floating'}}).success,false,'only supported placements may be saved');
assert.equal(restored.invitation.enabled,false);
assert.deepEqual(restored.business.services[0].inclusions,['Paint-safe wash','Wheel care']);
assert.equal(baseline.images.lightHeroId,'');
const legacy=structuredClone(defaultContent);delete legacy.invitation;delete legacy.images.lightHeroId;
assert.equal(parseContent(JSON.stringify(legacy)).invitation.enabled,true);
assert.equal(parseContent(JSON.stringify(legacy)).images.lightHeroId,'');
console.log('PASS: three public care choices, deliberate vehicle selection, clearly separated add-ons, package eligibility, theme artwork/inclusions/invitation round-trip, and legacy defaults. Browser rendering remains unverified.');

