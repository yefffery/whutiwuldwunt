b=business();b.package.visible=false;
assert.deepEqual(toggleBookingService(b,['exterior'],'interior'),['interior']);
assert.deepEqual(selectionFromFoundingInterest('I’m still deciding'),{selected:[],helpChoosing:true},'a recommendation choice clears any previously selected service');
